// ---------------------------------------------------------------------------
// generate.mjs — one token source, two surfaces.
//
// Reads design/tokens.json and writes:
//   src/renderer/src/styles/tokens.css   (desktop, CSS custom properties)
//   ../codezy-cli/src/tokens.mjs         (terminal, plain JS data)
//
// Both outputs are committed, so builds never depend on this script. It is
// dev-only and intentionally dependency-free: run `node design/generate.mjs`
// after editing tokens.json, then review the diff.
// ---------------------------------------------------------------------------

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(HERE, '..')
const TOKENS = JSON.parse(fs.readFileSync(path.join(HERE, 'tokens.json'), 'utf8'))

const THEMES = Object.keys(TOKENS.themes)
const LEGACY = TOKENS.legacyThemes || {}
const HEADER = '/* generated by design/generate.mjs — edit design/tokens.json, not this file */'

// -- CSS ---------------------------------------------------------------------

const themeOf = (name) => TOKENS.themes[name]
const aliasSelectors = (name) => {
  const aliases = Object.entries(LEGACY)
    .filter(([from, to]) => to === name && from !== name)
    .map(([from]) => `html[data-theme='${from}']`)
  return [`html[data-theme='${name}']`, ...aliases].join(',\n')
}

const themeVars = (name) => {
  const t = themeOf(name)
  return [
    `  --gs-bg-base: ${t.bg.base};`,
    `  --gs-bg-raised: ${t.bg.raised};`,
    `  --gs-bg-overlay: ${t.bg.overlay};`,
    `  --gs-bg-elevated: ${t.bg.elevated};`,
    `  --gs-bg-sunken: ${t.bg.sunken};`,
    `  --gs-line: ${t.line.base};`,
    `  --gs-line-strong: ${t.line.strong};`,
    `  --gs-text-hi: ${t.text.hi};`,
    `  --gs-text-mid: ${t.text.mid};`,
    `  --gs-text-low: ${t.text.low};`,
    `  --gs-signal: ${t.signal};`,
    `  --gs-signal-ink: ${t.signalInk};`,
    `  --gs-ok: ${t.ok};`,
    `  --gs-warn: ${t.warn};`,
    `  --gs-danger: ${t.danger};`,
    `  --gs-code: ${t.code};`,
    `  --gs-syntax-key: ${t.syntax.key};`,
    `  --gs-syntax-str: ${t.syntax.str};`,
    `  --gs-syntax-num: ${t.syntax.num};`,
    `  --gs-syntax-com: ${t.syntax.com};`,
    '',
    '  /* compatibility layer — same names the 3.1.x stylesheets already use */',
    '  --bg: var(--gs-bg-base);',
    '  --bg-1: var(--gs-bg-raised);',
    '  --bg-2: var(--gs-bg-overlay);',
    '  --bg-3: var(--gs-bg-elevated);',
    '  --sidebar: var(--gs-bg-raised);',
    '  --border: var(--gs-line);',
    '  --border-strong: var(--gs-line-strong);',
    '  --text: var(--gs-text-hi);',
    '  --text-2: var(--gs-text-mid);',
    '  --text-3: var(--gs-text-low);',
    '  --accent: var(--gs-signal);',
    '  --accent-2: var(--gs-signal);',
    '  --ok: var(--gs-ok);',
    '  --warn: var(--gs-warn);',
    '  --err: var(--gs-danger);',
    '  --bubble-user: var(--gs-bg-elevated);',
    '  --bubble-user-text: var(--gs-text-hi);',
    '  --code-bg: var(--gs-bg-sunken);',
    '  --shadow: 0 12px 40px rgba(0, 0, 0, 0.35);'
  ]
}

const themeBlock = (name) => {
  return [`${aliasSelectors(name)} {`, ...themeVars(name), '}'].join('\n')
}

const rootLines = [
  `${HEADER}`,
  '',
  ':root {',
  `  --gs-font-ui: ${TOKENS.fonts.ui};`,
  `  --gs-font-mono: ${TOKENS.fonts.mono};`,
  `  --gs-font-display: ${TOKENS.fonts.display};`,
  ...TOKENS.space.map((px, i) => `  --gs-space-${i}: ${px}px;`),
  ...Object.entries(TOKENS.radii).map(([k, v]) => `  --gs-radius-${k}: ${v}px;`),
  ...Object.entries(TOKENS.motion).map(([k, v]) => `  --gs-motion-${k}: ${v}ms;`),
  '',
  '  /* graphite is the default before a theme attribute lands */',
  ...themeVars('graphite'),
  '}',
  ''
].join('\n')

const css = [
  rootLines,
  ...THEMES.map((t) => `${themeBlock(t)}\n`),
  '/* reduced motion: the app also has an explicit switch; both flatten to 0 */',
  '@media (prefers-reduced-motion: reduce) {',
  '  :root { --gs-motion-fast: 0ms; --gs-motion-base: 0ms; }',
  '}',
  'html[data-motion=\'off\'] { --gs-motion-fast: 0ms; --gs-motion-base: 0ms; }',
  ''
].join('\n')

const cssOut = path.join(ROOT, 'src', 'renderer', 'src', 'styles', 'tokens.css')
fs.writeFileSync(cssOut, css)
console.log(`wrote ${path.relative(process.cwd(), cssOut)} (${THEMES.length} themes)`)

// -- CLI data ----------------------------------------------------------------

const cliDir = path.resolve(ROOT, '..', 'codezy-cli', 'src')
const cliOut = path.join(cliDir, 'tokens.mjs')
const data = {
  version: TOKENS.version,
  fonts: TOKENS.fonts,
  space: TOKENS.space,
  radii: TOKENS.radii,
  motion: TOKENS.motion,
  themes: TOKENS.themes,
  accents: TOKENS.accents,
  legacyThemes: LEGACY,
  defaultAccent: TOKENS.defaultAccent || 'blue'
}
const cli = `${HEADER}
// Runtime data only: theme.mjs owns ANSI/capability logic.

export const TOKENS = ${JSON.stringify(data, null, 2)}

export const THEMES = Object.keys(TOKENS.themes)
export const ACCENTS = TOKENS.accents
export const DEFAULT_THEME = 'graphite'
export const DEFAULT_ACCENT = TOKENS.defaultAccent
export const LEGACY_THEMES = TOKENS.legacyThemes
`
fs.mkdirSync(cliDir, { recursive: true })
fs.writeFileSync(cliOut, cli)
console.log(`wrote ${path.relative(process.cwd(), cliOut)}`)
